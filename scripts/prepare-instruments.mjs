// Fetch only data files from a pinned, attributed CC BY 3.0 sample collection.
// Drum one-shots are generated here, not sourced from third-party recordings.
import { execFile } from 'node:child_process'
import { promisify } from 'node:util'
import { mkdir, writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
const run = promisify(execFile)
const revision = '622c2f1c32c8cfce4158ddc3eb26e518ddef37e5'
const root = new URL('../public/samples/', import.meta.url)
const manifest = []
async function save(name, bytes, source) {
  await writeFile(new URL(name, root), bytes)
  manifest.push({ file: name, bytes: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex'), source })
}
await mkdir(root, { recursive: true })
const sets = { 'guitar-acoustic': ['E2', 'A3', 'C5'], 'guitar-electric': ['E2', 'A3', 'C5'], 'bass-electric': ['E1', 'E2', 'E3'] }
await Promise.all(Object.entries(sets).flatMap(([folder, notes]) => notes.map(async (note) => {
  const path = `samples/${folder}/${note}.mp3`
  const { stdout } = await run('gh', ['api', `repos/nbrosowsky/tonejs-instruments/contents/${path}?ref=${revision}`], { maxBuffer: 5e6, timeout: 45000 })
  const data = JSON.parse(stdout)
  if (data.encoding !== 'base64' || !data.content) throw new Error(`Missing sample: ${path}`)
  await save(`${folder}-${note}.mp3`, Buffer.from(data.content, 'base64'), `https://github.com/nbrosowsky/tonejs-instruments/blob/${revision}/${path}`)
})))
const sampleRate = 22050
for (const [name, seconds, frequency, noiseMix] of [['kick', .65, 52, .015], ['snare', .35, 180, .75], ['closed-hat', .12, 7000, .95], ['open-hat', .8, 7000, .95], ['low-tom', .55, 95, .06], ['mid-tom', .5, 135, .05], ['high-tom', .45, 190, .05], ['crash', 2.5, 3600, .85], ['ride', 1.5, 2800, .6]]) {
  const length = Math.ceil(seconds * sampleRate), bytes = Buffer.alloc(44 + length * 2)
  bytes.write('RIFF', 0); bytes.writeUInt32LE(bytes.length - 8, 4); bytes.write('WAVEfmt ', 8)
  bytes.writeUInt32LE(16, 16); bytes.writeUInt16LE(1, 20); bytes.writeUInt16LE(1, 22)
  bytes.writeUInt32LE(sampleRate, 24); bytes.writeUInt32LE(sampleRate * 2, 28); bytes.writeUInt16LE(2, 32); bytes.writeUInt16LE(16, 34)
  bytes.write('data', 36); bytes.writeUInt32LE(length * 2, 40)
  let seed = 42, phase = 0, previous = 0
  for (let i = 0; i < length; i++) {
    const t = i / sampleRate
    seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0
    const random = seed / 2 ** 31 - 1, noise = frequency > 2000 ? (random - previous) / 2 : random
    previous = random
    phase += 2 * Math.PI * frequency * (1 + (frequency < 200 ? 2 * Math.exp(-t * 50) : 0)) / sampleRate
    const tone = Math.sin(phase) + (frequency > 2000 ? .3 * Math.sin(phase * 1.47) : 0)
    const envelope = Math.min(1, t * 1500) * Math.exp(-t * 7 / seconds) * Math.min(1, (seconds - t) * 500)
    const value = Math.max(-1, Math.min(1, (tone * (1 - noiseMix) + noise * noiseMix) * envelope * .8))
    bytes.writeInt16LE(Math.round(value * 32767), 44 + i * 2)
  }
  await save(`drum-${name}.wav`, bytes, 'Generated by Sonora scripts/prepare-instruments.mjs; MIT')
}
manifest.sort((a, b) => a.file.localeCompare(b.file))
await writeFile(new URL('../assets/samples/expanded-manifest.json', import.meta.url), JSON.stringify({ revision, license: 'Guitar/bass: CC BY 3.0; original electronic drums: MIT', samples: manifest }, null, 2) + '\n')
console.log(`Prepared ${manifest.length} audio files (${manifest.reduce((sum, file) => sum + file.bytes, 0)} bytes).`)
